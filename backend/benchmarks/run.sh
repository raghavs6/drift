#!/usr/bin/env bash
# Drift latency benchmark runner — Phase 2, step 10.
#
# Every knob that could drift between the baseline run and the post-tuning run is
# pinned here rather than left to the shell. If a later run changes one of these,
# the delta stops being attributable to the code and the resume number is worthless.
#
#   ./benchmarks/run.sh baseline
#
# Run from the backend/ directory. Requires: k6, a running Postgres, and the schema
# migrated (docker compose up -d && alembic upgrade head).
set -euo pipefail

LABEL="${1:-baseline}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND="$(dirname "$HERE")"
OUT="$HERE/results/$LABEL"

# --- pinned run parameters -------------------------------------------------
# Deliberately not 8000: a dev server on the conventional port would be measured
# instead of the one this script configures, and none of the pinned env below
# would apply to it.
PORT=8001
MOCK_PORT=8787
MOCK_DELAY=2.0          # seconds per simulated LLM call
UVICORN_WORKERS=1       # single event loop: the step-11 blocking story needs this fixed
SEED_ROWS=2000
TOKEN_COUNT=200         # must be >= the highest VU level in load_test.js
PLANTRIP_PERIOD=5       # one plan-trip request every N seconds
CATALOG_LIMIT=500
REQUEST_TIMEOUT=60s      # slower than this is recorded as a failure, not a latency
export RATE_LIMIT_MAX_REQUESTS=1000000   # localhost load test is one IP; the 5/60s
export RATE_LIMIT_WINDOW_SECONDS=60      # default would 429 plan-trip immediately
export ANTHROPIC_BASE_URL="http://127.0.0.1:$MOCK_PORT"
export ANTHROPIC_API_KEY="benchmark-key-never-sent-anywhere-real"
# ---------------------------------------------------------------------------

cd "$BACKEND"
PY="$BACKEND/.venv/bin/python"
mkdir -p "$OUT"

# A port already in use means uvicorn silently fails to bind and every request goes
# to whatever else is listening — a benchmark of the wrong process, with none of the
# pinned settings below. Refuse rather than record a plausible-looking wrong number.
for p in "$PORT" "$MOCK_PORT"; do
  if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then
    echo "port $p is already in use:" >&2
    lsof -nP -iTCP:"$p" -sTCP:LISTEN >&2
    echo "stop it (or change PORT/MOCK_PORT in this script) and re-run." >&2
    exit 1
  fi
done

cleanup() {
  [[ -n "${APP_PID:-}"  ]] && kill "$APP_PID"  2>/dev/null || true
  [[ -n "${MOCK_PID:-}" ]] && kill "$MOCK_PID" 2>/dev/null || true
}
trap cleanup EXIT

echo "==> seeding $SEED_ROWS rows"
"$PY" benchmarks/seed.py --rows "$SEED_ROWS"

echo "==> minting $TOKEN_COUNT tokens"
"$PY" benchmarks/mint_token.py --count "$TOKEN_COUNT" --out benchmarks/tokens.json

echo "==> starting mock anthropic on :$MOCK_PORT"
"$PY" benchmarks/mock_anthropic.py --port "$MOCK_PORT" --delay "$MOCK_DELAY" \
  >"$OUT/mock.log" 2>&1 &
MOCK_PID=$!

echo "==> starting uvicorn on :$PORT ($UVICORN_WORKERS worker)"
"$BACKEND/.venv/bin/uvicorn" app.main:app --host 127.0.0.1 --port "$PORT" \
  --workers "$UVICORN_WORKERS" --log-level warning >"$OUT/server.log" 2>&1 &
APP_PID=$!

echo "==> waiting for /health"
for _ in $(seq 1 40); do
  curl -sf "http://127.0.0.1:$PORT/health" >/dev/null 2>&1 && break
  sleep 0.5
done
curl -sf "http://127.0.0.1:$PORT/health" >/dev/null

# Fail loudly now rather than recording a baseline full of 500s. A fast error is
# not a fast request.
echo "==> preflight"
TOKEN=$("$PY" -c "import json;print(json.load(open('benchmarks/tokens.json'))[0])")
for path in "/api/experiences?limit=1" "/api/preferences" "/api/swipes" "/api/collections"; do
  code=$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $TOKEN" \
    "http://127.0.0.1:$PORT$path")
  echo "    $path -> $code"
  [[ "$code" == "200" ]] || { echo "preflight failed on $path"; exit 1; }
done
code=$(curl -s -o /dev/null -w '%{http_code}' -X POST -H 'Content-Type: application/json' \
  -d '{"title":"preflight"}' "http://127.0.0.1:$PORT/api/plan-trip")
echo "    /api/plan-trip -> $code"
[[ "$code" == "200" ]] || { echo "preflight failed on /api/plan-trip"; exit 1; }

echo "==> running k6"
# k6 exits 99 when a threshold is crossed. At baseline that is an expected result -
# the point of a baseline is to record how bad it currently is - so capture the code
# and keep going rather than letting `set -e` discard the run's own conditions file.
K6_STATUS=0
BASE_URL="http://127.0.0.1:$PORT" \
TOKENS_FILE="$BACKEND/benchmarks/tokens.json" \
CATALOG_LIMIT="$CATALOG_LIMIT" \
PLANTRIP_PERIOD="$PLANTRIP_PERIOD" \
REQUEST_TIMEOUT="$REQUEST_TIMEOUT" \
k6 run --summary-mode full \
       --summary-export "$OUT/summary.json" \
       benchmarks/load_test.js 2>&1 | tee "$OUT/summary.txt" || K6_STATUS=$?
echo "    k6 exit status: $K6_STATUS"

echo "==> writing RESULTS.md"
{
  echo "# Benchmark run — \`$LABEL\`"
  echo
  echo "Generated by \`benchmarks/run.sh $LABEL\`. Absolute numbers are specific to this"
  echo "machine; only the delta against another run recorded under the same conditions"
  echo "is meaningful."
  echo
  echo "| Field | Value |"
  echo "|---|---|"
  echo "| Date (UTC) | $(date -u '+%Y-%m-%d %H:%M:%S') |"
  echo "| Git SHA | $(git -C "$BACKEND" rev-parse HEAD) |"
  echo "| Git branch | $(git -C "$BACKEND" rev-parse --abbrev-ref HEAD) |"
  echo "| Working tree | $(git -C "$BACKEND" diff --quiet && echo clean || echo dirty) |"
  echo "| Host | $(uname -srm) |"
  echo "| CPU | $(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown) |"
  echo "| Logical cores | $(sysctl -n hw.logicalcpu 2>/dev/null || nproc) |"
  echo "| Python | $("$PY" --version 2>&1) |"
  echo "| k6 | $(k6 version | head -1) |"
  echo "| Postgres | $(docker exec drift-postgres psql -U drift -d drift -tAc 'show server_version' 2>/dev/null || echo unknown) |"
  echo "| uvicorn workers | $UVICORN_WORKERS |"
  echo "| Rate limit | $RATE_LIMIT_MAX_REQUESTS per ${RATE_LIMIT_WINDOW_SECONDS}s |"
  echo "| Catalog limit | $CATALOG_LIMIT |"
  echo "| Request timeout | $REQUEST_TIMEOUT |"
  echo "| plan-trip cadence | 1 per ${PLANTRIP_PERIOD}s |"
  echo "| Mock LLM delay | ${MOCK_DELAY}s |"
  echo "| Seeded rows | $SEED_ROWS |"
  echo "| k6 exit status | $K6_STATUS (99 = a threshold was crossed) |"
  echo
  echo "### Catalog composition at run time"
  echo
  echo '```'
  docker exec drift-postgres psql -U drift -d drift \
    -c 'SELECT source, count(*) FROM experiences GROUP BY source ORDER BY 2 DESC;' 2>/dev/null \
    || echo "unavailable"
  echo '```'
  echo
  echo "### Engine configuration under test"
  echo
  echo '```'
  "$PY" - <<'PYINNER'
import sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd()))
from app.core.database import engine
p = engine.pool
print(f"pool class      : {type(p).__name__}")
print(f"pool_size       : {getattr(p, 'size', lambda: 'n/a')()}")
print(f"max_overflow    : {getattr(p, '_max_overflow', 'n/a')}")
print(f"pool_timeout    : {getattr(p, '_timeout', 'n/a')}")
print(f"pool_recycle    : {getattr(p, '_recycle', 'n/a')}")
print(f"pool_pre_ping   : {getattr(p, '_pre_ping', 'n/a')}")
PYINNER
  echo '```'
  echo
  echo "---"
  echo
  "$PY" benchmarks/summarize.py "$OUT/summary.json"
} > "$OUT/RESULTS.md"

echo
echo "==> done. results in benchmarks/results/$LABEL/"
ls -1 "$OUT"
