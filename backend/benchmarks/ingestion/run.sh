#!/usr/bin/env bash
# Drift ingestion-throughput benchmark - Phase 4, steps 20 and 24.
#
# Times a full nationwide catalog sync against an empty table. The baseline and the
# post-concurrency run must differ ONLY by the code under test, so everything that could
# drift between them is pinned here rather than left to the shell.
#
#   ./benchmarks/ingestion/run.sh baseline
#   ./benchmarks/ingestion/run.sh concurrent
#
# Run from the backend/ directory. Requires Docker Postgres up and real RIDB/NPS keys.
set -euo pipefail

LABEL="${1:?usage: run.sh <label>}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND="$(cd "$HERE/../.." && pwd)"
OUT="$HERE/$LABEL.md"

# --- pinned run parameters -------------------------------------------------
# A scratch database, never the dev one: both runs need an empty experiences table, and
# truncating `drift` would cascade into collection_items and destroy the Phase 2 bench rows.
export DATABASE_URL='postgresql+psycopg://drift:drift@localhost:5432/drift_bench'
PGDB=drift_bench
PGCONTAINER=drift-postgres
# ---------------------------------------------------------------------------

cd "$BACKEND"
PY="$BACKEND/.venv/bin/python"

# Without real keys every state fails, and a run that fetched nothing is not a fast run.
"$PY" - <<'PYCHECK' || exit 1
import sys
from app.core.config import settings

missing = [
    name
    for name, value in (("RIDB_API_KEY", settings.ridb_api_key), ("NPS_API_KEY", settings.nps_api_key))
    if not value
]
if missing:
    print(f"not configured: {', '.join(missing)} - the run would time error paths", file=sys.stderr)
    sys.exit(1)
PYCHECK

psql() { docker exec "$PGCONTAINER" psql -U drift -d "$PGDB" "$@"; }

echo "==> emptying $PGDB.experiences"
psql -qc 'TRUNCATE experiences CASCADE;'
[[ "$(psql -tAc 'SELECT count(*) FROM experiences;')" == "0" ]] || { echo "table not empty" >&2; exit 1; }

echo "==> syncing (this is the measurement)"
START=$(date +%s)
set +e
"$PY" -m app.scripts.sync_experiences 2>&1 | tee "$HERE/$LABEL.log"
SYNC_STATUS=${PIPESTATUS[0]}
set -e
END=$(date +%s)
ELAPSED=$((END - START))

ROWS=$(psql -tAc 'SELECT count(*) FROM experiences;')
FAILED=$(sed -n 's/.*Failed states: //p' "$HERE/$LABEL.log" | head -1)
FAILED=${FAILED:-"(sync did not report)"}

echo "==> writing $OUT"
{
  echo "# Ingestion run - \`$LABEL\`"
  echo
  echo "Generated by \`benchmarks/ingestion/run.sh $LABEL\`. Only the delta against another"
  echo "run recorded under the same conditions is meaningful."
  echo
  echo "| Field | Value |"
  echo "|---|---|"
  echo "| Date (UTC) | $(date -u '+%Y-%m-%d %H:%M:%S') |"
  echo "| Wall clock | **${ELAPSED}s** ($((ELAPSED / 60))m $((ELAPSED % 60))s) |"
  echo "| Rows in table | **$ROWS** |"
  echo "| Failed states | $FAILED |"
  echo "| Exit status | $SYNC_STATUS |"
  echo "| Git SHA | $(git rev-parse HEAD) |"
  echo "| Git branch | $(git rev-parse --abbrev-ref HEAD) |"
  echo "| Working tree | $(git diff --quiet && echo clean || echo dirty) |"
  echo "| Host | $(uname -srm) |"
  echo "| CPU | $(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown) |"
  echo "| Python | $("$PY" --version 2>&1) |"
  echo "| Database | $PGDB (truncated before the run) |"
  echo "| State concurrency | $("$PY" -c 'from app.services.sync import STATE_CONCURRENCY; print(STATE_CONCURRENCY)') |"
  echo
  echo "### Catalog composition after the run"
  echo
  echo '```'
  psql -c 'SELECT source, count(*) FROM experiences GROUP BY source ORDER BY 2 DESC;' || echo unavailable
  echo '```'
  echo
  echo "### Field variance (what step 15a was for)"
  echo
  echo '```'
  psql -c "SELECT category, count(*) FROM experiences GROUP BY category ORDER BY 2 DESC;" || echo unavailable
  psql -c "SELECT difficulty, count(*) FROM experiences GROUP BY difficulty ORDER BY 2 DESC;" || echo unavailable
  echo '```'
  echo
  echo "### Script output"
  echo
  echo '```'
  cat "$HERE/$LABEL.log"
  echo '```'
} > "$OUT"

echo
echo "==> done: ${ELAPSED}s, $ROWS rows, exit $SYNC_STATUS -> $OUT"
